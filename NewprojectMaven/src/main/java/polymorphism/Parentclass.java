package polymorphism;

public class Parentclass {
	
	public void display(int a, int b)
	{
		int sum= a+b;
		System.out.println(sum);
	}

	public int multiply(int a, int b)
	{
		int mul= a*b;
		return mul;
		
		
	}
	
	public void view ( float a, float b)
	{
		float c= a-b;
		System.out.println(c);
	}
	
}
